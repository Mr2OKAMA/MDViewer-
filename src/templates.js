/** テンプレートに沿って Markdown を作らせるための AI プロンプト。白紙など対象外は null */
export function buildPrompt(template, date = today()) {
  if (!template.promptRules) return null;
  const rules = [...COMMON_RULES, ...template.promptRules].map((x, i) => `${i + 1}. ${x}`).join('\n');
  return `あなたは業務手順書の作成を支援するアシスタントです。
下の「元の手順」に書かれたテキストを、「テンプレート」の構成どおりの「${template.name}」の Markdown ファイルに変換してください。

# ルール

${rules}

# テンプレート

<template>
${template.content(date)}</template>

# 元の手順

<source>
（ここに手順のテキストを貼り付けてください）
</source>
`;
}

